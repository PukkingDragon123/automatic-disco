/** the logo as a data URL at k px per stencil pixel (UI) */
const urls = new Map<string, string>();
export function logoURL(logo: LogoId, col: string, k = 2): string {
  const key = `${logo}|${col}|${k}`; let u = urls.get(key);
  if (u) return u;
  const c = document.createElement('canvas'); c.width = c.height = 12 * k;
  const x = c.getContext('2d')!; x.fillStyle = col;
  const g = LOGOS[logo];
  for (let j = 0; j < 12; j++) for (let i = 0; i < 12; i++) if (g[j][i] === '#') x.fillRect(i * k, j * k, k, k);
  u = c.toDataURL(); urls.set(key, u);
  return u;
}
