// Bakes the item icons: renders every real item's icon from its 3D model (res.html?bake, src/world/resources3d/icon.ts)
// at 32 and 64 px and writes src/inv/itemSprites.ts: one shared palette, the 32 px set as raw palette indices
// (SPRITES, 255 = clear) and the 64 px set run-length coded (SPRITES64: [count, index] byte pairs).
// Run from the repo root with the dev server up:  node src/world/resources3d/bake.mjs [http://localhost:5180]
import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire('/opt/node-tools/node_modules/');
const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:5180';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 800, height: 600 } });
page.setDefaultTimeout(600000);
page.on('pageerror', (e) => console.error('[pageerror]', e.message));
await page.goto(`${base}/src/world/resources3d/res.html?bake`, { waitUntil: 'load' });
await page.waitForFunction(() => !!window.__bake, null, { timeout: 600000, polling: 1000 });
const bake = await page.evaluate(() => window.__bake);
await browser.close();

const ids = Object.keys(bake);
// each icon carries its own small palette: [n colours, r g b * n] then its pixels (255 = clear)
const decode = (b64) => Buffer.from(b64, 'base64');
const pack = (rgba, rle) => {
  const pal = new Map(), n = rgba.length / 4, px = Buffer.alloc(n);
  for (let i = 0; i < n; i++) {
    if (rgba[i * 4 + 3] < 128) { px[i] = 255; continue; }
    const c = (rgba[i * 4] << 16) | (rgba[i * 4 + 1] << 8) | rgba[i * 4 + 2];
    let k = pal.get(c); if (k === undefined) { k = pal.size; pal.set(c, k); }
    if (k > 254) throw new Error('icon over 255 colours');
    px[i] = k;
  }
  const head = [pal.size]; for (const c of pal.keys()) head.push((c >> 16) & 255, (c >> 8) & 255, c & 255);
  let body = px;
  if (rle) { const out = []; for (let i = 0; i < px.length;) { let k = 1; while (i + k < px.length && px[i + k] === px[i] && k < 255) k++; out.push(k, px[i]); i += k; } body = Buffer.from(out); }
  return Buffer.concat([Buffer.from(head), body]).toString('base64');
};
const s32 = {}, s64 = {};
for (const id of ids) { s32[id] = pack(decode(bake[id][0]), true); s64[id] = pack(decode(bake[id][1]), true); }
const key = (id) => (/^[a-z_][a-z0-9_]*$/.test(id) ? id : JSON.stringify(id));
const lines = [
  "// GENERATED by src/world/resources3d/bake.mjs: every real item's icon rendered from its own 3D model",
  '// (src/world/resources3d: a clean three-quarter view, shading along each material\'s own ramp, a strong lit lip and',
  '// rim, ink lines where parts overlap, a bold black outline). Do not edit by hand: change the models and run the bake.',
  '// Each entry is base64 of [n, r g b * n (its palette), then run-length pairs [count, index]] (index 255 = clear).',
  'export const SPRITE_SIZE = 32;',
  '/** item id -> the 32 x 32 icon */',
  'export const SPRITES: Record<string, string> = {',
  ...ids.map((id) => `  ${key(id)}: '${s32[id]}',`),
  '};',
  '/** item id -> the 64 x 64 icon */',
  'export const SPRITES64: Record<string, string> = {',
  ...ids.map((id) => `  ${key(id)}: '${s64[id]}',`),
  '};',
  '',
];
fs.writeFileSync('src/inv/itemSprites.ts', lines.join('\n'));
console.log('baked', ids.length, 'items,', Math.round(fs.statSync('src/inv/itemSprites.ts').size / 1024), 'KB');
