// Bakes the item icons: renders every real item's icon from its 3D model (res.html?bake, src/world/resources3d/icon.ts)
// at 32 and 64 px and writes src/inv/itemSprites.ts: one shared palette, the 32 px set as raw palette indices
// (SPRITES, 255 = clear) and the 64 px set run-length coded (SPRITES64: [count, index] byte pairs).
// Run from the repo root with the dev server up:  node src/world/resources3d/bake.mjs [http://localhost:5180]
import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire('/opt/node-tools/node_modules/');
const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:5180';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 800, height: 600 } });
page.setDefaultTimeout(600000);
page.on('pageerror', (e) => console.error('[pageerror]', e.message));
await page.goto(`${base}/src/world/resources3d/res.html?bake`, { waitUntil: 'load' });
await page.waitForFunction(() => !!window.__bake, null, { timeout: 600000, polling: 1000 });
const bake = await page.evaluate(() => window.__bake);
await browser.close();

const ids = Object.keys(bake);
const pal = new Map();
const idx = (r, g, b) => { const c = (r << 16) | (g << 8) | b; let i = pal.get(c); if (i === undefined) { i = pal.size; pal.set(c, i); } return i; };
const decode = (b64) => Buffer.from(b64, 'base64');
const toIdx = (rgba) => { const n = rgba.length / 4, out = Buffer.alloc(n); for (let i = 0; i < n; i++) out[i] = rgba[i * 4 + 3] < 128 ? 255 : idx(rgba[i * 4], rgba[i * 4 + 1], rgba[i * 4 + 2]); return out; };
const rle = (buf) => { const out = []; for (let i = 0; i < buf.length;) { let n = 1; while (i + n < buf.length && buf[i + n] === buf[i] && n < 255) n++; out.push(n, buf[i]); i += n; } return Buffer.from(out); };
const s32 = {}, s64 = {};
for (const id of ids) { s32[id] = toIdx(decode(bake[id][0])).toString('base64'); s64[id] = rle(toIdx(decode(bake[id][1]))).toString('base64'); }
if (pal.size > 255) throw new Error('palette over 255 colours: ' + pal.size);
const hex = [...pal.keys()].map((c) => '0x' + c.toString(16).padStart(6, '0'));
const lines = [
  '// GENERATED by src/world/resources3d/bake.mjs: every real item\'s icon rendered from its own 3D model',
  '// (src/world/resources3d: a clean three-quarter view, ramp shading in the master palette, a strong lit lip and rim,',
  '// ink lines where parts overlap, a bold black outline). Do not edit by hand: change the models and run the bake.',
  'export const SPRITE_SIZE = 32;',
  `export const SPRITE_PAL: number[] = [${hex.join(', ')}];`,
  '/** item id -> base64 of SPRITE_SIZE^2 palette indices (255 = clear) */',
  'export const SPRITES: Record<string, string> = {',
  ...ids.map((id) => `  ${/^[a-z_][a-z0-9_]*$/.test(id) ? id : JSON.stringify(id)}: '${s32[id]}',`),
  '};',
  '/** the 64 px set: item id -> base64 of run-length pairs [count, palette index] (255 = clear), 64 x 64 */',
  'export const SPRITES64: Record<string, string> = {',
  ...ids.map((id) => `  ${/^[a-z_][a-z0-9_]*$/.test(id) ? id : JSON.stringify(id)}: '${s64[id]}',`),
  '};',
  '',
];
fs.writeFileSync('src/inv/itemSprites.ts', lines.join('\n'));
console.log('baked', ids.length, 'items,', pal.size, 'colours,', Math.round(fs.statSync('src/inv/itemSprites.ts').size / 1024), 'KB');
